#!/usr/bin/env python3
"""Steer log: every decision and steer from the user, searchable.

Storage: <project>/STEER.jsonl, one JSON record per line, append-only (never rewritten by hand).
View:    <project>/STEER.md, generated by `render` (grouped by world part, what holds now first).

Record fields
  id          S-0001 ...
  when        "YYYY-MM-DD HH:MM" local (use "~" prefix on the time when estimated)
  stage       pipeline stage (A.3, B.2, C.1 ...) or ""
  affects     list of world parts from <project>/steer_parts.txt (the "which part" axis)
  topic       stable kebab-case key for the subject; the latest record on a topic holds
  said        the user's exact words, verbatim
  images      image paths the user picked or pointed at
  decision    what it means for the build, 1-2 sentences
  status      pending | in progress | done | applied
  supersedes  ids of earlier records on the same topic (filled automatically)
  refs        commits, briefs, files that carried it out

Commands
  add      --affects a,b --topic t --said "..." [--said "..."] --decision "..." [--stage] [--image p] [--status] [--when] [--ref]
           [--supersedes S-0012,S-0020]   also retire records on other topics that this steer overrides
  find     [--affects a] [--topic t] [--text words] [--image substr] [--since YYYY-MM-DD] [--all]
  current  [--affects a]       what holds now: latest record per topic, minus records retired by --supersedes
  topics                       topic -> latest id, count
  status   ID --status s [--ref r]   appends a status update record (never edits)
  render                       writes STEER.md
Run from the project folder or pass --project.
"""
import argparse, datetime, json, pathlib, sys

def paths(a):
    root = pathlib.Path(a.project).resolve()
    return root, root / "STEER.jsonl", root / "STEER.md", root / "steer_parts.txt"

def load(f):
    if not f.exists():
        return []
    return [json.loads(l) for l in f.read_text(encoding="utf-8").splitlines() if l.strip()]

def parts_of(pf):
    if not pf.exists():
        sys.exit(f"missing {pf}: one world part per line (copy .omp/templates/steer_parts.txt)")
    return [l.strip() for l in pf.read_text(encoding="utf-8").splitlines() if l.strip() and not l.startswith("#")]

def merged(recs):
    """Status updates (kind=update) fold into their target; returns decision records only."""
    by = {r["id"]: dict(r) for r in recs if r.get("kind", "steer") == "steer"}
    for r in recs:
        if r.get("kind") == "update" and r["target"] in by:
            t = by[r["target"]]
            t["status"] = r["status"]
            t["refs"] = t.get("refs", []) + r.get("refs", [])
    return list(by.values())

def holds(recs):
    """What holds now: the latest record per topic, minus any record another record lists in `supersedes`."""
    latest = {}
    for r in recs:
        latest[r["topic"]] = r
    retired = {s for r in recs for s in r.get("supersedes", [])}
    return set(id(r) for r in latest.values() if r["id"] not in retired), latest

def line(r, now=True):
    imgs = f" · images: {', '.join(r['images'])}" if r.get("images") else ""
    st = r.get("status", "")
    said = " / ".join(f"“{s}”" for s in r["said"])
    tag = "" if now else " ~~(superseded)~~"
    return (f"- **{r['id']}** {r['when']} · `{r['topic']}` · {', '.join(r['affects'])}{' · ' + r['stage'] if r.get('stage') else ''}"
            f"{tag}\n  - said: {said}{imgs}\n  - means: {r['decision']} ({st})")

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--project", default=".")
    sp = ap.add_subparsers(dest="cmd", required=True)
    a = sp.add_parser("add")
    a.add_argument("--affects", required=True); a.add_argument("--topic", required=True)
    a.add_argument("--said", action="append", required=True); a.add_argument("--decision", required=True)
    a.add_argument("--stage", default=""); a.add_argument("--image", action="append", default=[])
    a.add_argument("--status", default="pending"); a.add_argument("--when"); a.add_argument("--ref", action="append", default=[])
    a.add_argument("--supersedes", default="", help="comma-separated ids on other topics this steer overrides")
    f = sp.add_parser("find")
    f.add_argument("--affects"); f.add_argument("--topic"); f.add_argument("--text"); f.add_argument("--image")
    f.add_argument("--since"); f.add_argument("--all", action="store_true", help="include superseded records")
    c = sp.add_parser("current"); c.add_argument("--affects")
    sp.add_parser("topics")
    s = sp.add_parser("status"); s.add_argument("id"); s.add_argument("--status", required=True); s.add_argument("--ref", action="append", default=[])
    sp.add_parser("render")
    args = ap.parse_args()
    root, jf, mf, pf = paths(args)
    recs = load(jf)

    if args.cmd == "add":
        allowed = parts_of(pf)
        aff = [x.strip() for x in args.affects.split(",") if x.strip()]
        bad = [x for x in aff if x not in allowed]
        if bad:
            sys.exit(f"unknown world part(s) {bad}; allowed: {', '.join(allowed)} (add new parts to {pf.name})")
        n = sum(1 for r in recs if r.get("kind", "steer") == "steer") + 1
        known = {r["id"] for r in merged(recs)}
        extra = [x.strip() for x in args.supersedes.split(",") if x.strip()]
        if [x for x in extra if x not in known]:
            sys.exit(f"unknown ids in --supersedes: {[x for x in extra if x not in known]}")
        prev = [r["id"] for r in merged(recs) if r["topic"] == args.topic] + extra
        rec = {"kind": "steer", "id": f"S-{n:04d}",
               "when": args.when or datetime.datetime.now().strftime("%Y-%m-%d %H:%M"),
               "stage": args.stage, "affects": aff, "topic": args.topic, "said": args.said,
               "images": args.image, "decision": args.decision, "status": args.status,
               "supersedes": prev, "refs": args.ref}
        with jf.open("a", encoding="utf-8") as fh:
            fh.write(json.dumps(rec, ensure_ascii=False) + "\n")
        print(rec["id"], "supersedes " + ", ".join(prev) if prev else "")
        render(merged(load(jf)), mf, root)
        return
    if args.cmd == "status":
        with jf.open("a", encoding="utf-8") as fh:
            fh.write(json.dumps({"kind": "update", "target": args.id, "status": args.status, "refs": args.ref,
                                 "when": datetime.datetime.now().strftime("%Y-%m-%d %H:%M")}, ensure_ascii=False) + "\n")
        render(merged(load(jf)), mf, root)
        return

    recs = merged(recs)
    now_ids, latest = holds(recs)
    if args.cmd == "render":
        render(recs, mf, root); print(mf); return
    if args.cmd == "topics":
        cnt = {}
        for r in recs:
            cnt[r["topic"]] = cnt.get(r["topic"], 0) + 1
        for t, r in sorted(latest.items(), key=lambda kv: kv[1]["when"], reverse=True):
            print(f"{t:28} {r['id']}  x{cnt[t]}  {', '.join(r['affects'])}")
        return
    sel = recs
    if args.cmd == "current":
        sel = [r for r in recs if id(r) in now_ids]
    else:
        if not args.all:
            sel = [r for r in sel if id(r) in now_ids]
        if args.topic: sel = [r for r in sel if r["topic"] == args.topic]
        if args.image: sel = [r for r in sel if any(args.image.lower() in i.lower() for i in r.get("images", []))]
        if args.since: sel = [r for r in sel if r["when"] >= args.since]
        if args.text:
            words = args.text.lower().split()
            sel = [r for r in sel if all(w in json.dumps(r, ensure_ascii=False).lower() for w in words)]
    if getattr(args, "affects", None):
        sel = [r for r in sel if args.affects in r["affects"]]
    for r in sel:
        print(line(r, id(r) in now_ids))

def render(recs, mf, root):
    now_ids, _ = holds(recs)
    parts = {}
    for r in recs:
        for p in r["affects"]:
            parts.setdefault(p, []).append(r)
    out = [f"# Steer log: {root.name}",
           "", "Generated from `STEER.jsonl` by `python .omp/scripts/steer.py render`. Never edit by hand; add with `steer.py add`.",
           "The latest record on a topic holds (user: \"if I comment on the same thing my last thing holds\").", ""]
    for p in sorted(parts):
        rs = sorted(parts[p], key=lambda r: r["when"], reverse=True)
        out.append(f"## {p}")
        out += [line(r, id(r) in now_ids) for r in rs if id(r) in now_ids]
        old = [r for r in rs if id(r) not in now_ids]
        if old:
            out.append(f"<details><summary>{len(old)} superseded</summary>\n")
            out += [line(r, False) for r in old]
            out.append("\n</details>")
        out.append("")
    mf.write_text("\n".join(out), encoding="utf-8")

if __name__ == "__main__":
    main()
